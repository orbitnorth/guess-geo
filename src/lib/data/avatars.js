export function getAvatarById(id) {
  const resolvedId = LEGACY_MAP[id] || id
  return AVATARS.find((a) => a.id === resolvedId) || AVATARS[0]
}

export function getAvatarSrc(id) {
  const avatar = getAvatarById(id)
  return avatar ? avatar.src : AVATARS[0].src
}
